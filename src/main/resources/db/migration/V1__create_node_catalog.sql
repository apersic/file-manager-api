CREATE UNIQUE INDEX uq_node_single_root ON node ((parent_id IS NULL)) WHERE parent_id IS NULL;

CREATE INDEX ix_node_name_key ON node (name_key, id);

CREATE FUNCTION node_reject_parent_update()
RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
    IF NEW.parent_id IS DISTINCT FROM OLD.parent_id THEN
        RAISE EXCEPTION 'parent_id cannot be updated';
    END IF;
    RETURN NEW;
END;
$$;

CREATE TRIGGER trg_node_parent_immutable
BEFORE UPDATE OF parent_id ON node
FOR EACH ROW
EXECUTE FUNCTION node_reject_parent_update();
