CREATE TABLE node (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    parent_id BIGINT,
    kind VARCHAR(16) NOT NULL,
    name VARCHAR(255) NOT NULL,
    name_key VARCHAR(255) COLLATE "C" GENERATED ALWAYS AS (lower(name COLLATE "C")) STORED NOT NULL,
    parent_kind VARCHAR(16) NOT NULL DEFAULT 'FOLDER',
    created_at TIMESTAMPTZ(6) NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ(6) NOT NULL DEFAULT now(),
    CONSTRAINT ck_node_kind CHECK (kind IN ('FILE', 'FOLDER')),
    CONSTRAINT ck_node_name_length CHECK (char_length(name) BETWEEN 1 AND 255),
    CONSTRAINT ck_node_name_trimmed CHECK (name = btrim(name)),
    CONSTRAINT ck_node_name_reserved CHECK (name NOT IN ('.', '..')),
    CONSTRAINT ck_node_name_slash CHECK (
        position('/' IN name) = 0 AND position(chr(92) IN name) = 0
    ),
    CONSTRAINT ck_node_root_shape CHECK (
        (parent_id IS NULL AND kind = 'FOLDER') OR parent_id IS NOT NULL
    ),
    CONSTRAINT ck_node_parent_kind CHECK (parent_kind = 'FOLDER'),
    CONSTRAINT uq_node_id_kind UNIQUE (id, kind),
    CONSTRAINT uq_node_sibling_name UNIQUE (parent_id, name_key),
    CONSTRAINT fk_node_parent FOREIGN KEY (parent_id, parent_kind) REFERENCES node (id, kind) ON DELETE CASCADE
);

